/** The app intentionally uses a single dark "trading terminal" theme. */
@Composable
fun CoinPulseTheme(content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = CoinPulseColors,
        typography = CoinPulseTypography,
        shapes = CoinPulseShapes,
        content = content,
    )
}

